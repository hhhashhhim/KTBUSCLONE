const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { parse, compileTemplate } = require('@vue/compiler-sfc');
const file = 'resources/js/pages/booking/BookingPage.vue';
const source = fs.readFileSync(file, 'utf8');
const parsed = parse(source);
assert.deepEqual(parsed.errors, []);
assert.deepEqual(compileTemplate({ source: parsed.descriptor.template.content, filename: file, id: 'test' }).errors, []);
assert.ok(source.includes('<TicketActivityModal ref="ticketActivity" />'));
assert.ok(source.includes('@click="$refs.ticketActivity.open()"'));
assert.ok(source.includes('firstScheduleDrop?.at_display'));
assert.ok(source.includes('firstScheduleDrop?.by'));
assert.ok(source.includes('First dropped on'));
assert.ok(source.includes('v-for="event in dropHistory"'));
assert.ok(source.includes('role="alert"'));
assert.ok(!source.includes('labelDrop'));
const method = parsed.descriptor.script.content.match(/async busDropCheck\(\) \{([\s\S]*?)\n        \},/)[1];
const check = vm.runInNewContext('(async function () {' + method + '})');
(async () => {
    const state = { dropCheckRequestId: 0, addForm: {}, callApi: async () => ({ status: 200, data: { checkDrop: { drop_by: null, dropped_at_display: null } } }) };
    await check.call(state); assert.equal(state.hideDivButtonsDrop, false); assert.ok(state.droppedSchedule);
    state.callApi = async () => ({ status: 200, data: { checkDrop: null, firstDrop: { at_display: '26-Sep-2026 08:00 AM', by: 'First user' }, dropHistory: [{ action: 'First drop' }, { action: 'Reactivated' }] } });
    await check.call(state); assert.equal(state.hideDivButtonsDrop, true); assert.equal(state.dropHistory.length, 2);
    assert.equal(state.firstScheduleDrop.by, 'First user', 'Reactivation retains first drop summary');
    state.callApi = async () => ({ status: 200, data: { checkDrop: { drop_by: { name: 'Second user' } }, firstDrop: { by: 'First user' }, dropHistory: [{}, {}, {}] } });
    await check.call(state); assert.equal(state.hideDivButtonsDrop, false); assert.equal(state.firstScheduleDrop.by, 'First user');
    state.callApi = async () => ({ status: 200, data: { checkDrop: null } });
    await check.call(state); assert.equal(state.hideDivButtonsDrop, true); assert.equal(state.droppedSchedule, null);
    assert.equal(state.firstScheduleDrop, null); assert.equal(state.dropHistory.length, 0);
    let resolveOld;
    state.callApi = () => new Promise(resolve => { resolveOld = resolve; });
    const old = check.call(state);
    state.callApi = async () => ({ status: 200, data: { checkDrop: null } });
    await check.call(state);
    resolveOld({ status: 200, data: { checkDrop: { reason: 'Old selection' } } }); await old;
    assert.equal(state.droppedSchedule, null, 'Old responses cannot mark the next schedule as dropped');
    console.log('PASS booking ticket modal, alert template, missing actor, reverted drop and stale response guard');
})().catch(error => { console.error(error); process.exitCode = 1; });
